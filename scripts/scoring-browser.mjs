    browser=await chromium.launch();
    const context=await browser.newContext({viewport:{width:1440,height:1000},locale:'id-ID',timezoneId:'Asia/Jakarta'});
    admin=await context.newPage();admin.setDefaultTimeout(15000);admin.on('pageerror',error=>errors.push(error.message));
    await admin.goto('http://localhost:3005/login');
    await admin.getByLabel('Email',{exact:true}).fill('super@example.test');
    await admin.getByLabel('Password',{exact:true}).fill(fixturePassword);
    await admin.getByRole('button',{name:/\bLogin$/}).click();
    await expect(admin).toHaveURL(/\/dashboard$/);
    let releaseRubric;
    const rubricGate=new Promise(resolve=>{releaseRubric=resolve;});
    const rubricURL=`**/v2/activities/${activity.id}/scoring/rubric`;
    await admin.route(rubricURL,async route=>{await rubricGate;await route.continue();});
    await admin.goto(`http://localhost:3005/activity/${activity.id}?tab=scoring`);
    await expect(admin.getByRole('heading',{name:activity.name,exact:true})).toBeVisible();
    await expect(admin.locator('.ant-skeleton').first()).toBeVisible();
    await evidence(admin,'admin-loading-desktop');
    releaseRubric();
    await expect(admin.getByRole('heading',{name:'Penilaian kegiatan'})).toBeVisible();
    await admin.unroute(rubricURL);
    await admin.getByRole('button',{name:'Simpan rubrik',exact:true}).click();
    await expect(admin.getByText('Tambahkan setidaknya satu kelompok')).toBeVisible();
    await admin.getByRole('button',{name:'Tambah kelompok',exact:true}).click();
    await admin.getByLabel('Nama kelompok',{exact:true}).fill('Mujtahid');
    await admin.getByLabel('Aspek 1',{exact:true}).fill('Shiddiq');
    await admin.getByRole('button',{name:'Tambah aspek',exact:true}).click();
    await admin.getByLabel('Aspek 2',{exact:true}).fill('Amanah');
    await admin.getByLabel('Nilai maksimum',{exact:true}).nth(1).fill('50');
    await admin.getByLabel('Bobot',{exact:true}).nth(1).fill('3');
    await admin.getByRole('button',{name:'Tambah indeks',exact:true}).click();
    await admin.getByLabel('Indeks',{exact:true}).fill('B');
    await admin.getByRole('button',{name:'Tambah indeks',exact:true}).click();
    await admin.getByLabel('Indeks',{exact:true}).nth(1).fill('A');
    await admin.getByLabel('Nilai minimum (0–100)',{exact:true}).nth(1).fill('80');
    await admin.getByLabel('Catatan untuk semua peserta',{exact:true}).fill('Terus belajar dan menjaga amanah.');
    await admin.getByRole('button',{name:'Tambah kelompok',exact:true}).click();
    await admin.getByRole('button',{name:'Hapus kelompok',exact:true}).last().click();
    await admin.getByRole('button',{name:'Tambah aspek',exact:true}).click();
    await admin.getByRole('button',{name:'Hapus aspek 3',exact:true}).click();
    await admin.getByRole('button',{name:'Naikkan aspek 2',exact:true}).click();
    await admin.getByRole('button',{name:'Naikkan aspek 2',exact:true}).click();
    await admin.getByRole('button',{name:'Tambah indeks',exact:true}).click();
    await admin.getByRole('button',{name:'Hapus indeks',exact:true}).last().click();
    await evidence(admin,'admin-rubric-desktop');
    await admin.setViewportSize({width:390,height:844});await evidence(admin,'admin-rubric-mobile');
    await admin.getByRole('button',{name:'Simpan rubrik',exact:true}).click();
    await expect(admin.getByText('Rubrik tersimpan.',{exact:true})).toBeVisible();
    await admin.getByRole('tab',{name:'Nilai peserta',exact:true}).click();
    await admin.getByRole('button',{name:'Isi nilai',exact:true}).click();
    let dialog=admin.getByRole('dialog',{name:'Penilaian: Peserta Penilaian'});
    await dialog.getByLabel('Shiddiq (maks. 100, bobot 1)',{exact:true}).fill('100');
    await dialog.getByLabel('Amanah (maks. 50, bobot 3)',{exact:true}).fill('35');
    await dialog.getByLabel('Catatan peserta',{exact:true}).fill('Catatan peserta pertama.');
    await evidence(admin,'admin-entry-mobile');
    await dialog.getByRole('button',{name:'Simpan draf',exact:true}).click();
    await expect(dialog).not.toBeVisible();
    await expect(admin.getByText('77,5',{exact:true})).toBeVisible();
    await admin.getByRole('tab',{name:'Rubrik penilaian',exact:true}).click();
    await expect(admin.getByText('Rubrik terkunci karena nilai sudah diisi')).toBeVisible();
    await admin.getByRole('tab',{name:'Nilai peserta',exact:true}).click();
    const download=admin.waitForEvent('download');
    await admin.getByRole('button',{name:'Unduh templat Excel',exact:true}).click();
    const file=await download;const filePath=resolve(directory,'template.xlsx');await file.saveAs(filePath);
    const book=new (legacyRequire('exceljs').Workbook)();await book.xlsx.readFile(filePath);book.getWorksheet('Scores').getCell('F3').value=40;
    await admin.locator('input[type="file"]').setInputFiles({name:'scores.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:Buffer.from(await book.xlsx.writeBuffer())});
    const preview=admin.getByRole('dialog',{name:'Tinjau impor nilai'});
    await expect(preview.getByRole('button',{name:'Simpan 1 draf',exact:true})).toBeEnabled();
